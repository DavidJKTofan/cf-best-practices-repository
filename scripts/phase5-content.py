#!/usr/bin/env python3
"""Generate/check the opt-in, disposable Phase 5 snapshot. Never operates remotely.

Default: check generated SQL. --write: regenerate it after authored JSON review.
These IDs are local rehearsal identities, NOT production reservations/publications.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/phase5/starters.json"
TARGET = ROOT / "data/phase5/local-starters.sql"


def quote(value):
    return "'" + str(value).replace("'", "''") + "'"


def compact(value):
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def generate():
    entries = json.loads(SOURCE.read_text())
    ids = [entry["id"] for entry in entries]
    if ids != list(range(810001, 810005)):
        raise ValueError("Keep the four explicit disposable rehearsal identities")
    sql = [
        "-- GENERATED by scripts/phase5-content.py --write; edit starters.json instead.",
        "-- DISPOSABLE LOCAL REHEARSAL ONLY. Never an active/remote publication patch.",
        "-- No real role/review approval is implied. Publish through the editorial workflow",
        "-- after independent review/approval, allocating real IDs there, not these IDs.",
        "-- Fail closed on occupied IDs, altered snapshots and deleted-ID high-water marks.",
    ]
    prepared = []
    for entry in entries:
        id, c = entry["id"], entry["content"]
        fields = {
            "schema_version": c["schemaVersion"], "content_type": c["type"],
            "title": c["title"], "summary": c["summary"], "primary_family": c["primaryFamily"],
            "applicability_json": compact(c["applicability"]), "body_json": compact(c["body"]),
            "evidence": c["evidence"], "maturity": c["maturity"], "modified_at": c["modifiedAt"],
            "fact_verified_at": c["factVerifiedAt"], "review_due_at": c["reviewDueAt"],
        }
        taxa = [(kind, slug) for kind, key in (("family", "families"), ("product", "products"), ("outcome", "outcomes")) for slug in c[key]]
        comparisons = [f"r.{key} IS {quote(value)}" for key, value in fields.items()]
        comparisons += [
            "e.legacy_practice_id IS NULL", f"e.published_revision_id = {id}",
            "json_extract(r.lifecycle_json, '$.state') = 'active'",
            "json_extract(r.lifecycle_json, '$.reason') IS NULL",
            "json_extract(r.lifecycle_json, '$.supersededBy') IS NULL",
            f"(SELECT COUNT(*) FROM CatalogRevisionTaxa WHERE revision_id = {id}) = {len(taxa)}",
            f"(SELECT COUNT(*) FROM CatalogRevisionSources WHERE revision_id = {id}) = {len(c['sources'])}",
        ]
        comparisons += [f"EXISTS (SELECT 1 FROM CatalogRevisionTaxa WHERE revision_id = {id} AND kind = {quote(kind)} AND slug = {quote(slug)})" for kind, slug in taxa]
        comparisons += [f"EXISTS (SELECT 1 FROM CatalogRevisionSources WHERE revision_id = {id} AND position = {pos} AND url = {quote(s['url'])} AND title = {quote(s['title'])})" for pos, s in enumerate(c["sources"])]
        exact = f"SELECT 1 FROM CatalogEntries e JOIN CatalogRevisions r ON r.revision_id = e.published_revision_id JOIN CatalogPublications p ON p.practice_id = e.practice_id AND p.revision_id = r.revision_id WHERE e.practice_id = {id} AND " + " AND ".join(comparisons)
        occupied = f"EXISTS (SELECT 1 FROM CatalogEntries WHERE practice_id = {id}) OR EXISTS (SELECT 1 FROM CatalogRevisions WHERE revision_id = {id} OR practice_id = {id})"
        high_water = f"NOT EXISTS (SELECT 1 FROM CatalogEntries WHERE practice_id = {id}) AND EXISTS (SELECT 1 FROM sqlite_sequence WHERE name IN ('BestPractices', 'CatalogEntries') AND seq >= {id})"
        sql.append(f"INSERT INTO CatalogEntries (practice_id) SELECT 0 WHERE (({occupied}) AND NOT EXISTS ({exact})) OR ({high_water});")
        prepared.append((id, c, fields, taxa))
    for id, c, fields, taxa in prepared:
        sql.append(f"INSERT INTO CatalogEntries (practice_id) SELECT {id} WHERE NOT EXISTS (SELECT 1 FROM CatalogEntries WHERE practice_id = {id});")
        columns = ", ".join(["revision_id", "practice_id", *fields])
        values = ", ".join([str(id), str(id), *(quote(v) for v in fields.values())])
        sql.append(f"INSERT INTO CatalogRevisions ({columns}) SELECT {values} WHERE NOT EXISTS (SELECT 1 FROM CatalogRevisions WHERE revision_id = {id});")
        for kind, slug in taxa:
            sql.append(f"INSERT INTO CatalogRevisionTaxa (revision_id, kind, slug) SELECT {id}, {quote(kind)}, {quote(slug)} WHERE NOT EXISTS (SELECT 1 FROM CatalogRevisionTaxa WHERE revision_id = {id} AND kind = {quote(kind)} AND slug = {quote(slug)});")
        for pos, source in enumerate(c["sources"]):
            sql.append(f"INSERT INTO CatalogRevisionSources (revision_id, position, url, title) SELECT {id}, {pos}, {quote(source['url'])}, {quote(source['title'])} WHERE NOT EXISTS (SELECT 1 FROM CatalogRevisionSources WHERE revision_id = {id} AND position = {pos});")
        sql.append(f"INSERT INTO CatalogPublications (practice_id, revision_id, published_at) SELECT {id}, {id}, {quote(c['modifiedAt'])} WHERE NOT EXISTS (SELECT 1 FROM CatalogPublications WHERE revision_id = {id});")
        sql.append(f"UPDATE CatalogEntries SET published_revision_id = {id} WHERE practice_id = {id} AND published_revision_id IS NULL;")
    return "\n".join(sql) + "\n"


if __name__ == "__main__":
    expected = generate()
    if sys.argv[1:] == ["--write"]:
        TARGET.write_text(expected)
        print("Generated disposable local starter SQL; not authorized for remote use.")
    elif sys.argv[1:]:
        raise SystemExit(__doc__)
    elif not TARGET.exists() or TARGET.read_text() != expected:
        raise SystemExit("Stale Phase 5 SQL: review JSON, then python3 scripts/phase5-content.py --write")
    else:
        print("PASS authored Phase 5 JSON/generated local SQL parity")
